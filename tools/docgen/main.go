// Command docgen writes the rule reference under docs/rules from the embedded rules. Run it with `make docs`; CI fails if the committed docs are stale.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/nexutils/StackGuard/internal/loader"
	"github.com/nexutils/StackGuard/internal/models"
	"github.com/nexutils/StackGuard/internal/parser/all"
	"github.com/nexutils/StackGuard/rules"
)

var targetTitles = map[string]string{
	"ansible": "Ansible", "compose": "Docker Compose", "dockerfile": "Dockerfile",
	"github": "GitHub Actions", "helm": "Helm", "jenkins": "Jenkins",
	"kubernetes": "Kubernetes", "nginx": "nginx", "terraform": "Terraform",
}

func main() {
	out := flag.String("out", "docs/rules", "output directory")
	flag.Parse()
	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, "docgen:", err)
		os.Exit(1)
	}
}

func run(outDir string) error {
	set, err := loader.Load(
		loader.Options{KnownTargets: all.Registry().Names()},
		loader.Layer{Name: "embedded", FS: rules.FS, Embedded: true},
	)
	if err != nil {
		return err
	}
	byTarget := map[string][]*models.Rule{}
	for _, r := range set.All() {
		byTarget[r.Target] = append(byTarget[r.Target], r)
	}
	targets := make([]string, 0, len(byTarget))
	for t := range byTarget {
		targets = append(targets, t)
	}
	sort.Strings(targets)

	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}

	var idx bytes.Buffer
	idx.WriteString("<!-- Generated by tools/docgen. DO NOT EDIT. -->\n# Rule reference\n\n")
	fmt.Fprintf(&idx, "StackGuard ships %d built-in rules. Run `stackguard explain <RULE_ID>` for the same information in your terminal.\n\n", set.Len())
	idx.WriteString("| Target | Rules |\n|---|---|\n")
	for _, t := range targets {
		fmt.Fprintf(&idx, "| [%s](%s.md) | %d |\n", title(t), t, len(byTarget[t]))
	}
	idx.WriteString("\n## All rules\n\n| ID | Severity | Category | Title |\n|---|---|---|---|\n")
	for _, r := range set.All() {
		fmt.Fprintf(&idx, "| [%s](%s.md#%s) | %s | %s | %s |\n", r.ID, r.Target, strings.ToLower(r.ID), r.Severity, r.Category, r.Title)
	}
	if err := os.WriteFile(filepath.Join(outDir, "README.md"), idx.Bytes(), 0o644); err != nil {
		return err
	}

	for _, t := range targets {
		var b bytes.Buffer
		fmt.Fprintf(&b, "<!-- Generated by tools/docgen. DO NOT EDIT. -->\n# %s rules\n\n", title(t))
		for _, r := range byTarget[t] {
			fmt.Fprintf(&b, "## %s\n\n**%s**\n\n", r.ID, r.Title)
			fmt.Fprintf(&b, "| Severity | Category | Applies to |\n|---|---|---|\n| %s | %s | %s |\n\n", r.Severity, r.Category, appliesTo(r))
			if r.Description != "" {
				b.WriteString(r.Description + "\n\n")
			}
			if r.Remediation != "" {
				b.WriteString("**Remediation:** " + r.Remediation + "\n\n")
			}
			if len(r.References) > 0 {
				b.WriteString("**References:**\n\n")
				for _, ref := range r.References {
					fmt.Fprintf(&b, "- <%s>\n", ref)
				}
				b.WriteString("\n")
			}
			if r.QueryYAML != "" {
				b.WriteString("<details><summary>Query</summary>\n\n```yaml\n" + r.QueryYAML + "```\n\n</details>\n\n")
			}
		}
		if err := os.WriteFile(filepath.Join(outDir, t+".md"), b.Bytes(), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func title(t string) string {
	if s, ok := targetTitles[t]; ok {
		return s
	}
	return t
}

func appliesTo(r *models.Rule) string {
	if len(r.Resources) == 0 {
		return "all " + r.Target + " resources"
	}
	return "`" + strings.Join(r.Resources, "`, `") + "`"
}
